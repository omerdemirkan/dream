/**
 * How the prompt strings are put together from the section files in docs/prompts/, and the map of them in its
 * README. Shared by the sync script and the drift test so both agree.
 */
import { type PromptLayout, type PromptName, prompts, type SkillName, skillLayout, skillNames } from "./sections.ts"

export interface Section {
  /** The file, relative to docs/prompts/. */
  readonly file: string
  /** The one line its frontmatter gives on what it covers, for the map. */
  readonly covers: string
  /** Its heading, or "(opening)" for an opening section without one. */
  readonly heading: string
  /** What goes into the prompt: everything after the frontmatter. */
  readonly body: string
  readonly words: number
}

export const countWords = (text: string) => text.split(/\s+/).filter((word) => word.length > 0).length

/** A section file is `---`, a `covers: …` line, `---`, then its body, which opens with a heading unless it opens the prompt. */
export const parseSection = (file: string, markdown: string): Section => {
  const lines = markdown.split("\n")
  const end = lines.indexOf("---", 1)
  if (lines[0] !== "---" || end === -1) throw new Error(`${file}: expected frontmatter between \`---\` lines`)
  const covers = lines
    .slice(1, end)
    .map((line) => /^covers:\s*(.*)$/.exec(line)?.[1])
    .find((value) => value !== undefined)
    ?.replace(/^"(.*)"$/, "$1")
    .replace(/\\"/g, '"')
  if (covers === undefined || covers === "") throw new Error(`${file}: expected a \`covers:\` line in its frontmatter`)
  const body = lines
    .slice(end + 1)
    .join("\n")
    .trim()
  const heading = /^#+ (.*)$/.exec(body.split("\n")[0] ?? "")?.[1]
  return { file, covers, heading: heading ?? "(opening)", body, words: countWords(body) }
}

export interface BuiltPrompt {
  /** A system prompt's name, or a skill's. */
  readonly name: PromptName | SkillName
  readonly layout: PromptLayout
  /** A skill's frontmatter, as written between the `---` lines. */
  readonly frontmatter?: string
  readonly sections: ReadonlyArray<Section>
  readonly text: string
}

const build = (name: PromptName | SkillName, prompt: PromptLayout, read: (path: string) => string): BuiltPrompt => {
  const sections = prompt.sections.map((section) => {
    const file = `${prompt.dir}/${section}.md`
    return parseSection(file, read(file))
  })
  const frontmatter = prompt.frontmatter === undefined ? undefined : read(`${prompt.dir}/${prompt.frontmatter}`).trim()
  const head = frontmatter === undefined ? "" : `---\n${frontmatter}\n---\n\n`
  const text = head + sections.map((section) => section.body).join("\n\n") + "\n"
  return { name, layout: prompt, ...(frontmatter === undefined ? {} : { frontmatter }), sections, text }
}

/** Builds every prompt, the system prompt first, then the skills, then the task prompt; `read` gets a path relative to docs/prompts/. */
export const buildPrompts = (read: (path: string) => string): ReadonlyArray<BuiltPrompt> => [
  build("systemPrompt", prompts.systemPrompt, read),
  ...skillNames.map((name) => build(name, skillLayout(name), read)),
  build("taskPrompt", prompts.taskPrompt, read)
]

/** The two system prompts, and each skill as its SKILL.md (frontmatter included), in `skillNames` order. */
export const extractPrompts = (
  read: (path: string) => string
): { readonly systemPrompt: string; readonly taskPrompt: string; readonly skills: ReadonlyArray<string> } => {
  const built = buildPrompts(read)
  const text = (name: string) => built.find((prompt) => prompt.name === name)?.text ?? ""
  return {
    systemPrompt: text("systemPrompt"),
    taskPrompt: text("taskPrompt"),
    skills: skillNames.map(text)
  }
}

/** A skill's description, from its frontmatter. */
export const descriptionOf = (frontmatter: string): string | undefined =>
  /^description:\s*(.+)$/m.exec(frontmatter)?.[1]?.trim()

/** The map's markers in docs/prompts/README.md; what's between them is generated. */
export const mapStart = "<!-- map: generated by `bun run sync-prompts`; edit the sections, not this -->"
export const mapEnd = "<!-- /map -->"

const cell = (text: string) => text.replace(/\|/g, "\\|")

/** The tables between the markers: each prompt's sections in order, what each covers, and its size. */
export const renderMap = (built: ReadonlyArray<BuiltPrompt>): string =>
  built
    .map((prompt) => {
      const total = prompt.sections.reduce((sum, section) => sum + section.words, 0)
      const rows = prompt.sections.map(
        (section, i) =>
          `| ${i + 1} | [${cell(section.heading)}](${section.file}) | ${cell(section.covers)} | ${section.words} |`
      )
      const description = prompt.frontmatter === undefined ? undefined : descriptionOf(prompt.frontmatter)
      return [
        `### ${prompt.layout.title}, ${total.toLocaleString("en-US")} words`,
        "",
        prompt.layout.role,
        ...(description === undefined
          ? []
          : [
              "",
              `Its description (${countWords(description)} words, in [frontmatter.yaml](${prompt.layout.dir}/frontmatter.yaml)): ${description}`
            ]),
        "",
        "| # | Section | Covers | Words |",
        "| --- | --- | --- | --- |",
        ...rows
      ].join("\n")
    })
    .join("\n\n")

/** README.md with its map brought up to date. */
export const withMap = (readme: string, built: ReadonlyArray<BuiltPrompt>): string => {
  const start = readme.indexOf(mapStart)
  const end = readme.indexOf(mapEnd)
  if (start === -1 || end < start) throw new Error(`docs/prompts/README.md: expected the map's markers`)
  return `${readme.slice(0, start + mapStart.length)}\n\n${renderMap(built)}\n\n${readme.slice(end)}`
}
