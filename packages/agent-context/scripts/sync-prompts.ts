/**
 * Regenerates src/generated/prompts.ts, and the map in docs/prompts/README.md, from the section files in
 * docs/prompts/ (their order is src/sections.ts). Run after editing any of them:
 *
 *   bun run sync-prompts
 *
 * test/prompts.test.ts fails if either is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { buildPrompts, withMap } from "../src/extract.ts"

const docs = (path: string) => fileURLToPath(new URL(`../../../docs/prompts/${path}`, import.meta.url))
const built = buildPrompts((path) => readFileSync(docs(path), "utf8"))
const text = Object.fromEntries(built.map((prompt) => [prompt.name, JSON.stringify(prompt.text)]))

const out = `// Generated by scripts/sync-prompts.ts from the sections in docs/prompts/, in the order src/sections.ts gives.
// Do not edit; edit the sections and run \`bun run sync-prompts\`.

/** The agent's whole system prompt. */
export const systemPrompt: string = ${text.systemPrompt}

/** The \`dream\` skill (SKILL.md, frontmatter included). */
export const dreamSkill: string = ${text.dreamSkill}

/** The whole system prompt of a scheduled task's session (\`dream wake --task\`). */
export const taskPrompt: string = ${text.taskPrompt}
`
writeFileSync(fileURLToPath(new URL("../src/generated/prompts.ts", import.meta.url)), out)
writeFileSync(docs("README.md"), withMap(readFileSync(docs("README.md"), "utf8"), built))
console.log("wrote src/generated/prompts.ts and the map in docs/prompts/README.md")
