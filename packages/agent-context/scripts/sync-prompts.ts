/**
 * Regenerates src/generated/prompts.ts from the canonical markdown in docs/.
 * Run after editing docs/agent-context.md, docs/dream-skill.md or docs/task-context.md:
 *
 *   bun run --filter @dream/agent-context sync
 *
 * test/prompts.test.ts fails if the generated module is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { extractPrompts } from "../src/extract.ts"

const read = (path: string) => readFileSync(fileURLToPath(new URL(path, import.meta.url)), "utf8")
const { systemPrompt, dreamSkill, taskPrompt } = extractPrompts({
  agentContext: read("../../../docs/agent-context.md"),
  dreamSkill: read("../../../docs/dream-skill.md"),
  taskContext: read("../../../docs/task-context.md")
})

const out = `// Generated by scripts/sync-prompts.ts from docs/agent-context.md, docs/dream-skill.md and docs/task-context.md.
// Do not edit; edit the docs and run \`bun run --filter @dream/agent-context sync\`.

/** The agent's whole system prompt. */
export const systemPrompt: string = ${JSON.stringify(systemPrompt)}

/** The \`dream\` skill (SKILL.md, frontmatter included). */
export const dreamSkill: string = ${JSON.stringify(dreamSkill)}

/** The whole system prompt of a scheduled task's session (\`dream wake --task\`). */
export const taskPrompt: string = ${JSON.stringify(taskPrompt)}
`
writeFileSync(fileURLToPath(new URL("../src/generated/prompts.ts", import.meta.url)), out)
console.log("wrote src/generated/prompts.ts")
